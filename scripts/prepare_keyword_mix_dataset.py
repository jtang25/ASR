#!/usr/bin/env python3
"""Prepare a keyword-focused Jerome Powell dataset with mix manifests.

Creates:
  <output-root>/9999                          (symlink to source 9999)
  <output-root>/targets/9999/<chapter>/*      (target-only clips + .trans.txt)
  <output-root>/target_utt_ids.txt
  <output-root>/non_target_utt_ids.txt
  <output-root>/keyword_occurrences_001_008.json
  <output-root>/summary.json
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
from pathlib import Path


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--source-root",
        default="dataset/JeromePowell",
        help="Source root containing 9999/<chapter>/*.flac and .trans.txt",
    )
    p.add_argument(
        "--keywords-json",
        default="dataset/JeromePowell_asr/keyword_occurrences_001_008.json",
        help="Keyword->utt_id JSON generated by scripts/find_keyword_occurrences.py",
    )
    p.add_argument(
        "--output-root",
        default="dataset/JeromePowell_keyword_mix",
        help="Output dataset root",
    )
    p.add_argument(
        "--target-link-mode",
        default="symlink",
        choices=["symlink", "hardlink", "copy"],
        help="How to materialize target-only FLAC files under output-root/targets",
    )
    return p.parse_args()


def _replace_path(dst: Path) -> None:
    if dst.is_symlink() or dst.is_file():
        dst.unlink()
    elif dst.is_dir():
        shutil.rmtree(dst)


def _symlink(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists() or dst.is_symlink():
        _replace_path(dst)
    rel = os.path.relpath(src, start=dst.parent)
    dst.symlink_to(rel)


def _materialize(src: Path, dst: Path, mode: str) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists() or dst.is_symlink():
        _replace_path(dst)
    if mode == "symlink":
        rel = os.path.relpath(src, start=dst.parent)
        dst.symlink_to(rel)
    elif mode == "hardlink":
        os.link(src, dst)
    elif mode == "copy":
        shutil.copy2(src, dst)
    else:  # pragma: no cover
        raise ValueError(f"Unsupported mode: {mode}")


def load_all_entries(source_root: Path) -> tuple[dict[str, str], dict[str, tuple[str, Path]], list[str]]:
    speaker_root = source_root / "9999"
    if not speaker_root.is_dir():
        raise FileNotFoundError(f"Missing source speaker root: {speaker_root}")

    text_by_utt: dict[str, str] = {}
    loc_by_utt: dict[str, tuple[str, Path]] = {}
    ordered_utts: list[str] = []

    chapter_dirs = sorted(p for p in speaker_root.iterdir() if p.is_dir() and p.name.isdigit())
    for chapter_dir in chapter_dirs:
        chapter = chapter_dir.name
        trans_path = chapter_dir / f"9999-{chapter}.trans.txt"
        if not trans_path.exists():
            continue
        for line in trans_path.read_text(encoding="utf-8").splitlines():
            parts = line.strip().split(None, 1)
            if len(parts) != 2:
                continue
            utt_id, text = parts
            flac_path = chapter_dir / f"{utt_id}.flac"
            if not flac_path.exists():
                continue
            text_by_utt[utt_id] = text
            loc_by_utt[utt_id] = (chapter, flac_path)
            ordered_utts.append(utt_id)
    return text_by_utt, loc_by_utt, ordered_utts


def main() -> None:
    args = parse_args()
    source_root = Path(args.source_root)
    keywords_json = Path(args.keywords_json)
    output_root = Path(args.output_root)

    if not keywords_json.exists():
        raise FileNotFoundError(f"Keyword JSON not found: {keywords_json}")

    keyword_map: dict[str, list[str]] = json.loads(keywords_json.read_text(encoding="utf-8"))
    target_utt_ids = sorted({utt for utts in keyword_map.values() for utt in utts})

    text_by_utt, loc_by_utt, ordered_utts = load_all_entries(source_root)
    all_utt_ids = [utt for utt in ordered_utts if utt in loc_by_utt]

    missing_targets = [utt for utt in target_utt_ids if utt not in loc_by_utt]
    kept_targets = [utt for utt in target_utt_ids if utt in loc_by_utt]
    target_set = set(kept_targets)
    non_target_utt_ids = [utt for utt in all_utt_ids if utt not in target_set]

    output_root.mkdir(parents=True, exist_ok=True)

    # Full dataset view for training (no duplication).
    _symlink(source_root / "9999", output_root / "9999")

    # Target-only materialized subset.
    target_root = output_root / "targets" / "9999"
    by_chapter: dict[str, list[str]] = {}
    for utt_id in kept_targets:
        chapter, flac_path = loc_by_utt[utt_id]
        by_chapter.setdefault(chapter, []).append(utt_id)
        out_flac = target_root / chapter / f"{utt_id}.flac"
        _materialize(flac_path, out_flac, args.target_link_mode)

    for chapter, utt_ids in by_chapter.items():
        utt_ids_sorted = sorted(utt_ids)
        lines = [f"{utt_id} {text_by_utt[utt_id]}" for utt_id in utt_ids_sorted]
        trans_path = target_root / chapter / f"9999-{chapter}.trans.txt"
        trans_path.parent.mkdir(parents=True, exist_ok=True)
        trans_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    (output_root / "keyword_occurrences_001_008.json").write_text(
        json.dumps(keyword_map, indent=2),
        encoding="utf-8",
    )
    (output_root / "target_utt_ids.txt").write_text("\n".join(sorted(kept_targets)) + "\n", encoding="utf-8")
    (output_root / "non_target_utt_ids.txt").write_text("\n".join(non_target_utt_ids) + "\n", encoding="utf-8")

    summary = {
        "source_root": str(source_root),
        "output_root": str(output_root),
        "target_link_mode": args.target_link_mode,
        "all_utterances": len(all_utt_ids),
        "target_utterances": len(kept_targets),
        "non_target_utterances": len(non_target_utt_ids),
        "target_fraction": (len(kept_targets) / len(all_utt_ids)) if all_utt_ids else 0.0,
        "missing_target_ids": missing_targets,
        "chapters_with_targets": sorted(by_chapter.keys()),
    }
    (output_root / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")

    print(f"Prepared dataset: {output_root}")
    print(f"All utterances: {len(all_utt_ids)}")
    print(f"Target utterances: {len(kept_targets)}")
    print(f"Non-target utterances: {len(non_target_utt_ids)}")
    print(f"Missing target IDs from source: {len(missing_targets)}")


if __name__ == "__main__":
    main()
